export function getRandomPack(lang: Lang, category: Category): SuggestionPack {
  if (category === 'meme') {
    // For memes, it's specific so we return a placeholder 
    // The actual suggestion pack is handled in the component when a meme is selected
    // But for fallback:
    const randomMeme = memes[Math.floor(Math.random() * memes.length)]
    const pack = randomMeme.suggestions[lang][0]
    return [...pack]
  }

  const packs = suggestions[lang]?.[category] ?? suggestions.fr[category] ?? suggestions.fr.passive
  return [...packs[Math.floor(Math.random() * packs.length)]]
}

export function getRandomMessage(lang: Lang, category: Category): MessagePack {
  if (category === 'meme') {
    // Pick a random meme
    const randomMeme = memes[Math.floor(Math.random() * memes.length)]
    // We return the encoded meme content as the second element (message content)
    // The first element is the sender name
    return ['Internet', memeToMessage(randomMeme)]
  }
  
  const packs = messagePacks[lang]?.[category] ?? messagePacks.fr[category] ?? messagePacks.fr.passive
  return [...packs[Math.floor(Math.random() * packs.length)]]
}


