export interface MemeContent {
  content: string
  sender: string
  suggestions: SuggestionPack
}

export function getRandomMemeContent(lang: Lang): MemeContent {
  const randomMeme = memes[Math.floor(Math.random() * memes.length)]
  const packs = randomMeme.suggestions[lang]
  const randomPack = packs[Math.floor(Math.random() * packs.length)]

  return {
    content: memeToMessage(randomMeme),
    sender: 'Internet',
    suggestions: [...randomPack]
  }
}



